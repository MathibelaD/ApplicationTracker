/** Builds an ad in the shape most job boards use, so the skills reader sees real sections. */
function jd({ about, does, req, nice = [], offer = OFFER }) {
  const list = (items) => items.map((x) => `- ${x}`).join("\n");
  return [
    "About us",
    about,
    "",
    "What you'll do",
    list(does),
    "",
    "Requirements",
    list(req),
    ...(nice.length ? ["", "Nice to have", list(nice)] : []),
    "",
    "What we offer",
    list(offer),
  ].join("\n");
}

